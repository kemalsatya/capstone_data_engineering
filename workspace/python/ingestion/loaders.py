# SRC-10: Indeks Kualitas Lingkungan Hidup (IKLH)
# -----------------------------------------------------------------------------
def load_src10():
    files = sorted((BASE_DIR / "SRC-10").glob("*.csv"))
    table = "raw.src10_iklh"
    cols = [
        "province", "indeks_kualitas_udara", "indeks_kualitas_air",
        "indeks_kualitas_tutupan_lahan", "indeks_kualitas_lahan",
        "indeks_kualitas_ekosistem_gambut", "indeks_kualitas_air_laut",
        "year_val", "_source_file"
    ]
    total = 0

    for fpath in files:
        # Extract year from filename or line 3
        year_str = "".join([c for c in fpath.stem if c.isdigit()])[-4:]
        year_val = int(year_str) if year_str else None
        
        def gen():
            with open(fpath, "r", encoding="utf-8-sig", errors="replace") as f:
                lines = [l for l in f]
                # data rows start from row index 4
                for line in lines[4:]:
                    parts = [p.strip() for p in line.split(",")]
                    if len(parts) >= 7 and parts[0]:
                        yield [parts[0], parts[1], parts[2], parts[3], parts[4], parts[5], parts[6], year_val, fpath.name]

        print(f"--> Ingesting SRC-10: {fpath.name} (Tahun {year_val})...")
        total += copy_from_stream(table, cols, gen)
    return total

