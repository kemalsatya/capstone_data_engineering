# SRC-02: BNPB / BPBD Disaster Records (Excel)
# -----------------------------------------------------------------------------
def load_src02():
    filepath = BASE_DIR / "SRC-02" / "data_bencana.xlsx"
    table = "raw.src02_disaster_records"
    columns = [
        "city_id", "event_date_serial", "disaster_type", "city", "province",
        "cause", "death", "missing_person", "injured_person", "damaged_house",
        "flooded_house", "damaged_facility", "_source_file"
    ]
    filename = filepath.name

    def gen():
        zf = zipfile.ZipFile(filepath)
        sst = []
        if 'xl/sharedStrings.xml' in zf.namelist():
            sst_xml = zf.read('xl/sharedStrings.xml')
            sst = [t.text for t in ET.fromstring(sst_xml).iter('{http://schemas.openxmlformats.org/spreadsheetml/2006/main}t')]
        
        sheet_xml = zf.read('xl/worksheets/sheet1.xml')
        sheet = ET.fromstring(sheet_xml)
        rows_elem = sheet.findall('{http://schemas.openxmlformats.org/spreadsheetml/2006/main}sheetData/{http://schemas.openxmlformats.org/spreadsheetml/2006/main}row')
        
        # Skip header row 0
        for r in rows_elem[1:]:
            cells = []
            for c in r.findall('{http://schemas.openxmlformats.org/spreadsheetml/2006/main}c'):
                t = c.attrib.get('t')
                v = c.find('{http://schemas.openxmlformats.org/spreadsheetml/2006/main}v')
                val = v.text if v is not None else ""
                if t == 's' and val != "" and int(val) < len(sst):
                    val = sst[int(val)]
                cells.append(val)
            # pad if missing
            while len(cells) < 12:
                cells.append("")
            yield cells[:12] + [filename]

    print(f"--> Ingesting SRC-02: {filename}...")
    return copy_from_stream(table, columns, gen)

