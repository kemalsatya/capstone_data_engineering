# SRC-01: BMKG Earthquake Catalog
# -----------------------------------------------------------------------------
def load_src01():
    filepath = BASE_DIR / "SRC-01" / "BMKG_Earthquake_Catalog.csv"
    table = "raw.src01_earthquake_catalog"
    columns = [
        "no_urutan", "event_id", "event_date", "time_utc", "latitude", "longitude",
        "magnitude", "mag_type", "depth_km", "source", "source_event_id", "_source_file"
    ]
    filename = filepath.name

    def gen():
        with open(filepath, "r", encoding="utf-8", errors="replace") as f:
            reader = csv.reader(f)
            next(reader, None) # skip header
            for row in reader:
                if len(row) < 12:
                    continue
                # row: No, Event ID, <empty>, Date, Time (UTC), Latitude, Longitude, Magnitude, Mag Type, Depth (km), Source, Source Event ID
                yield [
                    row[0].strip(), row[1].strip(), row[3].strip(), row[4].strip(),
                    row[5].strip(), row[6].strip(), row[7].strip(), row[8].strip(),
                    row[9].strip(), row[10].strip(), row[11].strip(), filename
                ]

    print(f"--> Ingesting SRC-01: {filename}...")
    return copy_from_stream(table, columns, gen)

