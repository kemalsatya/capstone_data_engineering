"""
Data Ingestion Loaders for Capstone Data Engineering
Streams transformed/cleaned data from workspace/data/Sumber Data/ into PostgreSQL raw.* tables
using high-performance PostgreSQL COPY protocol.
"""

import os
import sys
import csv
import json
import zipfile
import subprocess
import xml.etree.ElementTree as ET
from pathlib import Path
from datetime import datetime

BASE_DIR = Path(__file__).resolve().parents[2] / "data" / "Sumber Data"
PROJECT_ROOT = Path(__file__).resolve().parents[2]

NULL_LITERALS = {"", "-", "--", "...", "....", "na", "n/a", "null", "none", "nan", "#n/a", "#value!", "#ref!"}

def is_null_val(v):
    if v is None:
        return True
    s = str(v).strip()
    return s.lower() in NULL_LITERALS

def get_psql_cmd():
    """Returns the base command to pipe COPY data into PostgreSQL."""
    return ["docker", "compose", "exec", "-T", "postgres", "psql", "-U", "labuser", "-d", "labdata"]

def copy_from_stream(table_name, columns, row_generator):
    r"""
    Executes PostgreSQL \copy from STDIN streaming rows generated by row_generator.
    """
    col_str = ", ".join(columns)
    copy_sql = f"\\copy {table_name} ({col_str}) FROM STDIN WITH (FORMAT CSV, HEADER FALSE, NULL '\\N');"
    
    cmd = get_psql_cmd() + ["-c", copy_sql]
    
    # Run subprocess streaming stdin
    proc = subprocess.Popen(
        cmd,
        cwd=str(PROJECT_ROOT),
        stdin=subprocess.PIPE,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        encoding="utf-8"
    )
    
    writer = csv.writer(proc.stdin, lineterminator="\n")
    row_count = 0
    try:
        for row in row_generator():
            # Format row: replace empty string, missing symbols, or None with \N for NULL
            cleaned_row = ["\\N" if is_null_val(v) else str(v).strip() for v in row]
            writer.writerow(cleaned_row)
            row_count += 1
            if row_count % 50000 == 0:
                print(f"      ... streamed {row_count:,} rows")
        proc.stdin.close()
        stdout, stderr = proc.communicate()
        if proc.returncode != 0:
            raise RuntimeError(f"psql COPY failed for {table_name}: {stderr}")
        print(f"    [OK] Loaded {row_count:,} rows into {table_name}")
    except Exception as e:
        proc.kill()
        raise e
    return row_count

