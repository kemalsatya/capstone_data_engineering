# SRC-11: Spasial Batas Wilayah Administrasi (Level 0, 1, 2)
# -----------------------------------------------------------------------------
def load_src11():
    table = "raw.src11_admin_boundaries"
    cols = [
        "admin_level", "pcode", "name", "parent_pcode", "parent_name",
        "center_lat", "center_lon", "area_sqkm", "geom_geojson", "_source_file"
    ]
    total = 0
    targets = [
        ("idn_admin0.geojson", 0, "adm0_pcode", "adm0_name", None, None),
        ("idn_admin1.geojson", 1, "adm1_pcode", "adm1_name", "adm0_pcode", "adm0_name"),
        ("idn_admin2.geojson", 2, "adm2_pcode", "adm2_name", "adm1_pcode", "adm1_name"),
    ]

    for fname, lvl, p_code_k, name_k, parent_p_k, parent_n_k in targets:
        fpath = BASE_DIR / "SRC-11" / fname
        if not fpath.exists():
            continue

        print(f"--> Ingesting SRC-11: {fname} (Level {lvl})...")
        def gen():
            with open(fpath, "r", encoding="utf-8") as f:
                data = json.load(f)
            for feat in data.get("features", []):
                p = feat.get("properties", {})
                geom = json.dumps(feat.get("geometry", {}))
                pcode = p.get(p_code_k)
                name = p.get(name_k)
                par_pcode = p.get(parent_p_k) if parent_p_k else "ID"
                par_name = p.get(parent_n_k) if parent_n_k else "Indonesia"
                clat = p.get("center_lat")
                clon = p.get("center_lon")
                area = p.get("area_sqkm")
                yield [lvl, pcode, name, par_pcode, par_name, clat, clon, area, geom, fname]

        total += copy_from_stream(table, cols, gen)
    return total

